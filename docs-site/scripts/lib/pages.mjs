/** A short, stable digest of exactly the data a page renders. */
function digest(data) {
  return createHash('sha256').update(JSON.stringify(data)).digest('hex').slice(0, 12);
}

/** The banner every generated page opens with. */
function generatedBanner() {
  return callout(
    "**Generated page** — every table below is read out of the app's own source when this site is",
    'built. Do not edit this file by hand: `pnpm run check` and `pnpm run build` regenerate it and',
    'fail when what is committed here disagrees with the source.'
  );
}

