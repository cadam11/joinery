/** One command's palette cell: "Yes", "Yes — needs …", or "No — the catalogue's own reason". */
function paletteCell(palette) {
  if (!palette.inPalette) return `No — ${cell(palette.note)}`;
  return palette.note === null ? 'Yes' : `Yes — ${cell(palette.note)}`;
}

/** Each distinct reason a command is kept out of the palette, in catalogue order, with its count. */
function hiddenReasons(rows) {
  const counts = new Map();
  for (const row of rows.filter(candidate => !candidate.palette.inPalette)) {
    counts.set(row.palette.reason, (counts.get(row.palette.reason) ?? 0) + 1);
  }
  return [...counts.entries()];
}

