/** The provenance section: what was read, what came out, and how to regenerate it. */
function provenance(sources, mechanism, dataDigest) {
  return [
    '## How this page is generated',
    '',
    '`docs-site/scripts/generate-reference.mjs` reads these files and writes this page:',
    '',
    sources.map(source => `- \`${source}\``).join('\n'),
    '',
    mechanism,
    '',
    paragraph(
      `Data digest: \`${dataDigest}\` — a fingerprint of exactly the values rendered above. It`,
      'changes when what the app ships changes, and not when an unrelated comment in one of those',
      'files does.'
    ),
    '',
    'Regenerate from `docs-site/` with `pnpm run generate:reference`.',
  ].join('\n');
}

/** Menu / App / Editor, in the words the reader needs, without re-telling the feature page. */
const SOURCE_LABELS = { menu: 'Menu', renderer: 'App', editor: 'Editor' };

function sourceLabel(source) {
  const label = SOURCE_LABELS[source];
  if (label === undefined) {
    throw new Error(
      `The catalogue has an accelerator source this generator does not know: \`${source}\`. ` +
        'Add it to SOURCE_LABELS in docs-site/scripts/lib/pages.mjs.'
    );
  }
  return label;
}

